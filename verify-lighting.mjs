import assert from 'node:assert/strict';
import * as T from './dist/three.js';
import {environmentState,environmentLighting,Atmosphere} from './dist/weather-system.js';
import {Immersion} from './dist/immersion.js';
import {EnvironmentDetail} from './dist/environment-detail.js';

// Real scene objects validate lighting state transitions without claiming GPU QA.
globalThis.devicePixelRatio=1;
globalThis.document={body:{classList:{toggle(){}}}};
const scene=new T.Scene();scene.background=new T.Color();scene.fog=new T.FogExp2();
const renderer={shadowMap:{},setPixelRatio(){}},camera=new T.PerspectiveCamera();camera.position.set(54,1.7,-94);
const sun=new T.DirectionalLight();scene.add(sun,new T.HemisphereLight());
const immersion=new Immersion(scene,renderer,camera,sun,new T.Group(),new T.Group());
const detail=new EnvironmentDetail(scene,{textures:false});
const atmosphere=new Atmosphere(scene,renderer,camera,sun,immersion);
const state={elapsed:0,leg:1},settings={graphics:'HIGH',weather:'dusk',sunHour:13.5,movingSun:false,scanOverlay:true};
const update=()=>atmosphere.update(.016,state,settings,false);
update();
const daylight={sun:sun.intensity,ambient:atmosphere.hemi.reduce((n,h)=>n+h.intensity,0),environment:scene.environmentIntensity};
assert(daylight.sun>2.8,'Ordinary daylight has a strong directional key');
assert(daylight.ambient>2,'Shaded geometry retains diffuse illumination');
assert(daylight.environment>.8,'Metals receive a readable reflected sky');
settings.weather='storm';update();
assert(sun.intensity<daylight.sun*.4,'Cloud cover suppresses direct sun');
assert(atmosphere.hemi.reduce((n,h)=>n+h.intensity,0)>daylight.ambient*.8,'Overcast daylight preserves diffuse fill');
assert(atmosphere.rain.visible);
settings.weather='dusk';settings.sunHour=17.5;update();
assert(atmosphere.hemi[0].intensity>.9,'Legacy late afternoon is readable, including old saves');
settings.weather='night';settings.movingSun=true;state.elapsed=720;update();
assert.equal(atmosphere.frame.hour,0,'Night selection stays locked through a full cycle');
assert(sun.intensity<.1&&scene.environmentIntensity<.1,'Night retains its deliberate contrast');
assert(sun.position.y>camera.position.y,'Moonlight illuminates from above ground');
settings.weather='blackout';update();
assert.equal(sun.intensity,0);assert.equal(scene.environmentIntensity,0);
assert(atmosphere.hemi.every(h=>h.intensity===0));
assert.equal(immersion.sky.material.uniforms.top.value.getHex(),0);
assert.equal(immersion.sky.material.uniforms.bottom.value.getHex(),0);
settings.nightVision=true;update();assert(atmosphere.hemi[0].intensity>1&&scene.environmentIntensity>.4,'Intensifier recovers visibility from blackout');
settings.nightVision=false;settings.weather='dusk';settings.sunHour=13.5;settings.graphics='LOW';update();
assert.equal(immersion.sky.material.uniforms.cloudCover.value,0,'Low preset omits cloud shading');
assert.equal(environmentState({}).hour,13.5,'Missing sun time starts in daylight');
assert.equal(environmentState({sunHour:0}).hour,0,'An intentional midnight value survives');
assert.equal(environmentState({sunHour:-1}).hour,23,'Time wraps correctly');
for(const hour of [0,5,6,7,12,17.5,18,23.9])for(const weather of ['dusk','rain','storm','blackout','night'])for(const value of Object.values(environmentLighting(environmentState({hour,sunHour:hour,weather}))))assert(Number.isFinite(value)&&value>=0);
const {data,width,height}=detail.env.image,meanAt=y=>Array.from({length:width},(_,x)=>{const i=(y*width+x)*4;return(data[i]+data[i+1]+data[i+2])/3;}).reduce((a,b)=>a+b,0)/width;
assert(meanAt(height-1)>meanAt(0),'Environment reflection puts brighter sky above darker ground');
assert.equal(detail.env.colorSpace,T.SRGBColorSpace);
assert(immersion.sky.material.fragmentShader.includes('#include <colorspace_fragment>'),'Custom sky uses renderer output color conversion');
console.log('PASS: readable day/overcast/legacy dusk; separate moonlight, blackout and NV; low-quality cloud budget; correctly oriented PBR sky.');
console.log('Daylight:',daylight);
